"""Default retry behaviour for the Fern-generated Control clients.

``core/http_client.py`` already implements exponential backoff, jitter and
``Retry-After`` parsing, but it is dormant: ``max_retries`` defaults to ``0``,
so a single transient upstream 5xx surfaces to the caller. That file is
regenerated by Fern, so the default is switched on from here instead — this
module is listed in ``.fernignore``.

Two quirks of the generated implementation are worth knowing about:

1. ``HttpClient.request`` declares ``retries: int = 2`` while the retry guard
   is ``if max_retries > retries``. The counter therefore starts at 2, so
   ``max_retries`` is effectively off by two — ``{"max_retries": 2}`` performs
   no retries at all. We pin ``retries=0`` on the outermost call so the knob
   means what it says.
2. Because the counter starts at 2, the first backoff would otherwise be
   ``0.5 * 2**2 = 2s`` rather than 0.5s. Pinning the counter fixes that too.

``stream()`` is deliberately left alone: replaying a partially-consumed
response body is not safe.
"""

from __future__ import annotations

import typing

DEFAULT_MAX_RETRIES = 3
"""Retry attempts after the initial request, for retryable responses.

With the backoff in ``core/http_client.py`` this adds at most ~3.5s of delay
(0.5s + 1s + 2s, each with up to 25% jitter subtracted) before giving up.
"""

# Only replay requests that are safe to repeat. A 5xx usually means the request
# never took effect, but "usually" is not "always": ``models.run`` uploads data
# and creates a billable model result, so a replayed 500 risks a duplicate
# execution. Callers who want retries on those can opt in per call with
# ``request_options={"max_retries": N}``.
IDEMPOTENT_METHODS = frozenset({"GET", "HEAD", "OPTIONS", "DELETE", "PUT"})


def install_default_retries(
    http_client: typing.Any,
    max_retries: int = DEFAULT_MAX_RETRIES,
) -> None:
    """Make ``http_client.request`` retry idempotent requests by default.

    Wraps the bound ``request`` method so every call made by the generated raw
    clients carries a ``max_retries`` value, unless the caller passed their own.
    Mutates ``http_client`` in place.
    """
    if max_retries <= 0:
        return

    original = http_client.request

    def request(
        *args: typing.Any,
        request_options: typing.Optional[typing.Dict[str, typing.Any]] = None,
        **kwargs: typing.Any,
    ) -> typing.Any:
        # An explicit per-call max_retries always wins, including 0 to opt out.
        if request_options is None or "max_retries" not in request_options:
            method = kwargs.get("method") or (args[1] if len(args) > 1 else "GET")
            if str(method).upper() in IDEMPOTENT_METHODS:
                request_options = {**(request_options or {}), "max_retries": max_retries}

        # retries=0 corrects the off-by-two in the generated counter. The
        # recursive call inside HttpClient.request resolves to this wrapper,
        # which is harmless: request_options already carries max_retries, and
        # the recursion supplies its own incremented `retries`.
        kwargs.setdefault("retries", 0)
        return original(*args, request_options=request_options, **kwargs)

    http_client.request = request
